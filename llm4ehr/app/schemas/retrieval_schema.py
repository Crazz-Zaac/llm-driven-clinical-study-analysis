from pydantic import BaseModel, Field
from app.schemas.source_document_schema import SourceDocument
from enum import Enum


class RetrievalScope(str, Enum):
    SPECIFIC_PAPER = "specific_paper"
    ALL_PAPERS = "all_papers"
    RELEVANT_PAPERS = "relevant_papers"


class RetrievedDocument(BaseModel):
    # add fields that are relevant for the retrieved documents, e.g., title, abstract, url, etc.
    article_id: str
    title: str
    url: str
    abstract: str
    combined_text: str = ""
    section: str = ""
    score: float


class QueryRequest(BaseModel):
    query: str = Field(..., description="The natural language query to be processed.")
    retrieval_scope: RetrievalScope = Field(
        default=RetrievalScope.ALL_PAPERS,
        description="Scope of retrieval: 'relevant_papers', 'all_papers', or 'specific_paper'.",
    )
    article_id: str | None = Field(
        default=None,
        description="The ID of the specific article to retrieve documents from. Optional when a paper title is included in the query.",
    )
    top_k: int = Field(
        default=5, ge=1, le=20, description="Number of documents to retrieve."
    )


class QueryResponse(BaseModel):
    response: str = Field(
        default="", description="The response generated by the LLM based on the query."
    )
    contexts: list[str] = Field(
        default_factory=list,
        description="List of context snippets retrieved from the vector database that were used to generate the response.",
    )
    llm_docs: list[RetrievedDocument] = Field(
        default_factory=list,
        description="List of documents retrieved from the vector database that were used to generate the response.",
    )
    source_documents: list[SourceDocument] = Field(
        default_factory=list,
        description="List of source documents (article_id, title, url, score) that were retrieved and returned in the API response.",
    )

from pydantic import BaseModel, Field
from typing import List, Optional
from enum import Enum

from app.schemas.source_document_schema import SourceDocument
from app.schemas.retrieval_schema import RetrievalScope


class ChatRole(str, Enum):
    """Enumeration for chat message roles"""

    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"


class HostedProvider(str, Enum):
    """Hosted chat provider selected by the frontend."""

    HUGGINGFACE = "huggingface"
    OPENAI = "openai"
    MISTRAL = "mistral"
    ANTHROPIC = "anthropic"


class ChatMessage(BaseModel):
    role: ChatRole = Field(
        ..., description="The role of the message sender (user, assistant, or system)."
    )
    content: str = Field(..., description="The content of the message.")


class ChatRequest(BaseModel):
    messages: List[ChatMessage] = Field(
        ..., description="A list of chat messages forming the conversation history."
    )
    include_contexts: Optional[bool] = Field(
        default=False,
        description="Whether to include context snippets in the response. Defaults to False.",
    )
    retrieval_scope: RetrievalScope = Field(
        default=RetrievalScope.RELEVANT_PAPERS,
        description="Scope used to retrieve documents for the chat response.",
    )
    article_id: Optional[str] = Field(
        default=None,
        description="Specific article ID to use when retrieval_scope is 'specific_paper'.",
    )
    temperature: float = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature for chat generation.",
    )
    max_tokens: int = Field(
        default=2048,
        ge=1,
        le=32768,
        description="Maximum number of tokens to generate.",
    )
    top_p: float = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling probability for chat generation.",
    )
    hosted_provider: Optional[HostedProvider] = Field(
        default=None,
        description="Hosted provider to use when calling the remote RAG endpoint.",
    )
    hosted_model_name: Optional[str] = Field(
        default=None,
        description="Hosted chat model ID to use when calling the remote RAG endpoint.",
    )
    hosted_api_key: Optional[str] = Field(
        default=None,
        description="Request-scoped API key for the selected hosted provider.",
        exclude=True,
    )


class ChatResponse(BaseModel):
    response: str = Field(
        ...,
        description="The response generated by the LLM based on the conversation history.",
    )
    source_documents: List[SourceDocument] | None = Field(
        default=None,
        description="List of source documents used to generate the response, if applicable.",
    )
    contexts: Optional[List[str]] = Field(
        default=None,
        description="List of context snippets retrieved from the vector database that were used to generate the response.",
    )
    retrieval_scope: RetrievalScope | None = Field(
        default=None,
        description="Scope used to retrieve documents for this response.",
    )
